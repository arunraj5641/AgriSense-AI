interface I18nContextType {
  lang: LanguageCode;
  setLang: (lang: LanguageCode) => void;
  t: (key: string) => string;
  languages: LanguageOption[];
}

const I18nContext = createContext<I18nContextType>({
  lang: 'en',
  setLang: () => {},
  t: (key: string) => key,
  languages: SUPPORTED_LANGUAGES,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<LanguageCode>(() => {
    if (typeof window !== 'undefined') {
      try {
        const saved = localStorage.getItem('agrisense_lang') as LanguageCode | null;
        if (saved && (saved === 'en' || saved === 'hi' || saved === 'ta' || saved === 'fr')) {
          document.documentElement.lang = saved;
          return saved;
        }
      } catch {}
    }
    return 'en';
  });

  useEffect(() => {
    // Cross-tab synchronization
    const handleStorageChange = (e: StorageEvent) => {
      if (e.key === 'agrisense_lang' && e.newValue) {
        const newLang = e.newValue as LanguageCode;
        if (newLang === 'en' || newLang === 'hi' || newLang === 'ta' || newLang === 'fr') {
          setLangState(newLang);
          document.documentElement.lang = newLang;
        }
      }
    };

    window.addEventListener('storage', handleStorageChange);
    return () => window.removeEventListener('storage', handleStorageChange);
  }, []);

  const setLang = useCallback((newLang: LanguageCode) => {
    setLangState(newLang);
    try {
      localStorage.setItem('agrisense_lang', newLang);
    } catch {}
    document.documentElement.lang = newLang;
  }, []);

  const t = useCallback(
    (key: string): string => {
      const dict = translations[lang] || translations.en;
      return dict[key] || translations.en[key] || key;
    },
    [lang]
  );

  return (
    <I18nContext.Provider value={{ lang, setLang, t, languages: SUPPORTED_LANGUAGES }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useTranslation() {
  return useContext(I18nContext);
}
